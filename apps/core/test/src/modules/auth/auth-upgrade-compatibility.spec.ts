import { createHmac, randomUUID } from 'node:crypto'

import { hash } from 'bcryptjs'
import { verifyPassword } from 'better-auth/crypto'
import { createPgTestDatabase } from 'test/helper/pg-verify-url'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'

import { SECURITY } from '~/app.config'
import { CreateAuth } from '~/modules/auth/auth.implement'
import { __setTestPostgresInstance } from '~/processors/database/postgres.provider'
import { SnowflakeService } from '~/shared/id/snowflake.service'

describe('Better Auth upgrade with persisted credentials', () => {
  let context: Awaited<ReturnType<typeof createPgTestDatabase>>
  let auth: Awaited<ReturnType<typeof CreateAuth>>['auth']
  const password = 'pre-upgrade-password-123'
  // Generated by Better Auth 1.7.14, so this exercises the stored format
  // independently of the upgraded version's password writer.
  const legacyScryptHash =
    '7e90a56ae170bf1275faa629931ea76d:d2821a92915d5acd38858214536312ce1e820e45f665838fe8b21717f0b4c6e03f77fcbacd49b1882e7475205da1d746c60975f1e8ccf7bf166c97fe7997bb3b'

  beforeAll(async () => {
    context = await createPgTestDatabase('mx_auth_upgrade')
    __setTestPostgresInstance(context.pool, context.db)
    ;({ auth } = await CreateAuth(
      {},
      { rpID: 'localhost', origin: 'http://localhost:9528' },
      'http://localhost:2333',
      new SnowflakeService(),
    ))
  })

  afterAll(async () => {
    await context?.close()
  })

  async function seedOwner() {
    const id = randomUUID()
    const username = `owner_${id.replaceAll('-', '').slice(0, 16)}`
    await context.pool.query(
      `INSERT INTO readers (id, email, email_verified, name, username, role)
       VALUES ($1, $2, true, 'Existing Owner', $3, 'owner')`,
      [id, `${username}@example.test`, username],
    )
    return { id, username }
  }

  it.each(['bcrypt', 'scrypt'] as const)(
    'accepts a stored %s password without an account schema migration',
    async (algorithm) => {
      const owner = await seedOwner()
      const storedHash =
        algorithm === 'bcrypt' ? await hash(password, 4) : legacyScryptHash
      await context.pool.query(
        `INSERT INTO accounts (id, user_id, account_id, provider_id, password)
         VALUES ($1, $2, $2, 'credential', $3)`,
        [randomUUID(), owner.id, storedHash],
      )

      await expect(
        auth.api.signInUsername({
          body: { username: owner.username, password: 'incorrect-password' },
        }),
      ).rejects.toMatchObject({ status: 'UNAUTHORIZED' })

      const signIn = await auth.api.signInUsername({
        body: { username: owner.username, password },
      })
      expect(signIn.user.id).toBe(owner.id)
      const session = await auth.api.getSession({
        headers: new Headers({ authorization: `Bearer ${signIn.token}` }),
      })
      expect(session?.user.id).toBe(owner.id)

      const { rows } = await context.pool.query(
        "SELECT password FROM accounts WHERE user_id = $1 AND provider_id = 'credential'",
        [owner.id],
      )
      expect(await verifyPassword({ hash: rows[0].password, password })).toBe(
        true,
      )
    },
  )

  it('restores a legacy session from bearer and cookie credentials and rejects it after sign-out', async () => {
    const owner = await seedOwner()
    const token = randomUUID()
    await context.pool.query(
      `INSERT INTO sessions (id, user_id, token, expires_at)
       VALUES ($1, $2, $3, now() + interval '1 hour')`,
      [randomUUID(), owner.id, token],
    )
    const signature = createHmac('sha256', SECURITY.jwtSecret!)
      .update(token)
      .digest('base64')
    const bearerHeaders = new Headers({ authorization: `Bearer ${token}` })
    const cookieHeaders = new Headers({
      cookie: `better-auth.session_token=${encodeURIComponent(`${token}.${signature}`)}`,
    })

    for (const headers of [bearerHeaders, cookieHeaders]) {
      expect((await auth.api.getSession({ headers }))?.user.id).toBe(owner.id)
    }
    await auth.api.signOut({ headers: cookieHeaders })
    for (const headers of [bearerHeaders, cookieHeaders]) {
      expect(await auth.api.getSession({ headers })).toBeNull()
    }
  })
})
